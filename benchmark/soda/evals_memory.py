import argparse
import json
from collections import defaultdict
from typing import Any, Dict, List

try:
    from metrics.memory_recall import evidence_recall_at_k, estimate_memory_tokens
except Exception:
    from benchmark.soda.metrics.memory_recall import evidence_recall_at_k, estimate_memory_tokens


def _iter_questions(data: Dict[str, Any]):
    for conv_id, items in (data or {}).items():
        for it in items or []:
            yield str(conv_id), it


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate memory retrieval quality and token cost")
    parser.add_argument("--input_file", type=str, required=True, help="results.json generated by LOCOMO methods/search")
    parser.add_argument("--output_file", type=str, required=True, help="Path to save memory evaluation")
    parser.add_argument("--top_k", type=int, default=10)
    parser.add_argument("--dataset", type=str, default=None, help="Optional LOCOMO dataset path for resolving evidence dia_id")
    args = parser.parse_args()

    with open(args.input_file, "r", encoding="utf-8") as f:
        data = json.load(f) or {}

    dia_map: Dict[str, Dict[str, str]] = {}
    if args.dataset:
        try:
            with open(args.dataset, "r", encoding="utf-8") as f:
                ds = json.load(f) or []
            for idx, item in enumerate(ds):
                conv = (item or {}).get("conversation") or {}
                m: Dict[str, str] = {}
                for k, v in (conv or {}).items():
                    if not isinstance(k, str) or not k.startswith("session_") or k.endswith("_date_time"):
                        continue
                    if not isinstance(v, list):
                        continue
                    for chat in v:
                        if not isinstance(chat, dict):
                            continue
                        did = str(chat.get("dia_id") or "").strip()
                        txt = str(chat.get("text") or "").strip()
                        if did and txt:
                            m[did] = txt
                if m:
                    dia_map[str(idx)] = m
        except Exception:
            dia_map = {}

    by_category = defaultdict(list)
    rows: List[Dict[str, Any]] = []
    for conv_id, it in _iter_questions(data):
        cat = str(it.get("category", "-1"))
        if cat == "5":
            continue
        q = str(it.get("question") or "")
        ev_raw = it.get("evidence")
        ev = ev_raw
        if isinstance(ev_raw, list) and conv_id in dia_map:
            mapped = []
            for x in ev_raw:
                did = str(x or "").strip()
                mapped.append(dia_map.get(conv_id, {}).get(did, did))
            ev = mapped
        m1 = it.get("speaker_1_memories") or []
        m2 = it.get("speaker_2_memories") or []
        r1 = evidence_recall_at_k(ev, m1, k=args.top_k)
        r2 = evidence_recall_at_k(ev, m2, k=args.top_k)
        tok1 = estimate_memory_tokens(m1, k=args.top_k)
        tok2 = estimate_memory_tokens(m2, k=args.top_k)
        row = {
            "conversation": conv_id,
            "question": q,
            "category": cat,
            "speaker_1": {"tokens": tok1, **r1},
            "speaker_2": {"tokens": tok2, **r2},
        }
        rows.append(row)
        by_category[cat].append(row)

    summary: Dict[str, Any] = {"overall": {}, "by_category": {}}

    def agg(items: List[Dict[str, Any]]) -> Dict[str, Any]:
        if not items:
            return {"n": 0}
        n = len(items)
        t1 = sum(int((x.get("speaker_1") or {}).get("tokens") or 0) for x in items)
        t2 = sum(int((x.get("speaker_2") or {}).get("tokens") or 0) for x in items)

        def avg_recall(key: str) -> float:
            vals = []
            for x in items:
                v = (x.get(key) or {}).get("recall")
                if isinstance(v, (int, float)):
                    vals.append(float(v))
            return sum(vals) / len(vals) if vals else 0.0

        def hit_rate(key: str) -> float:
            vals = []
            for x in items:
                v = (x.get(key) or {}).get("hit")
                if v is True:
                    vals.append(1.0)
                elif v is False:
                    vals.append(0.0)
            return sum(vals) / len(vals) if vals else 0.0

        s1 = [x["speaker_1"] for x in items]
        s2 = [x["speaker_2"] for x in items]
        merged = [{"speaker_1": a, "speaker_2": b} for a, b in zip(s1, s2)]

        return {
            "n": n,
            "avg_tokens_speaker_1": t1 / n,
            "avg_tokens_speaker_2": t2 / n,
            "avg_tokens_total": (t1 + t2) / n,
            "hit_rate_speaker_1": hit_rate("speaker_1"),
            "hit_rate_speaker_2": hit_rate("speaker_2"),
            "avg_evidence_recall_speaker_1": avg_recall("speaker_1"),
            "avg_evidence_recall_speaker_2": avg_recall("speaker_2"),
        }

    summary["overall"] = agg(rows)
    for cat, items in by_category.items():
        summary["by_category"][cat] = agg(items)

    out = {"summary": summary, "items": rows}
    with open(args.output_file, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)


if __name__ == "__main__":
    main()
